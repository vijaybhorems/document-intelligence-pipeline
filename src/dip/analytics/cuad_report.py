"""Render the CUAD dataset profile (SPEC §14, Phase 1) from the SQL in analytics/queries/."""

from pathlib import Path

import duckdb

QUERIES_DIR = Path("analytics/queries")
VIEWS_SQL = Path("analytics/views.sql")

# (query file, heading, one-line reading guide)
SECTIONS: tuple[tuple[str, str, str], ...] = (
    (
        "cuad_text_layer",
        "PDF text layer",
        "Image-only PDFs would need OCR. Zero means CUAD is born-digital.",
    ),
    ("cuad_contract_types", "Contract types", "One of the split stratification labels."),
    (
        "cuad_splits",
        "Splits",
        "Frozen in data/splits.json. Test is scored only at milestones.",
    ),
    (
        "cuad_field_type_summary",
        "Prevalence by field type",
        "Share of contracts where a field is labelled.",
    ),
    (
        "cuad_field_prevalence",
        "Prevalence by field",
        "Rarest first. Rare fields are where recall will suffer.",
    ),
    (
        "cuad_test_support",
        "Positives per evaluation split",
        "Under 10 positives in test means wide confidence intervals.",
    ),
    (
        "cuad_label_issues",
        "Label issues",
        "Disagreements between CUAD's sources, or answers we couldn't normalize.",
    ),
)


def connect(data_dir: Path) -> duckdb.DuckDBPyConnection:
    con = duckdb.connect()
    views = VIEWS_SQL.read_text(encoding="utf-8").replace("'data/", f"'{data_dir.as_posix()}/")
    con.execute(views)
    return con


def _cell(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:g}"
    return str(value).replace("|", "\\|").replace("\n", " ")


def to_markdown(con: duckdb.DuckDBPyConnection, sql: str) -> str:
    relation = con.sql(sql)
    header = "| " + " | ".join(relation.columns) + " |"
    divider = "|" + "|".join("---" for _ in relation.columns) + "|"
    rows = ["| " + " | ".join(_cell(v) for v in row) + " |" for row in relation.fetchall()]
    return "\n".join([header, divider, *rows])


def render(data_dir: Path) -> str:
    con = connect(data_dir)
    parts = [
        "# CUAD dataset profile",
        "",
        "Generated by `dip cuad-report` from the queries in "
        "[`analytics/queries/`](../../analytics/queries/). Don't edit by hand; re-run the command.",
    ]
    for name, heading, guide in SECTIONS:
        sql = (QUERIES_DIR / f"{name}.sql").read_text(encoding="utf-8")
        parts += [
            "",
            f"## {heading}",
            "",
            f"{guide} Query: `{name}.sql`.",
            "",
            to_markdown(con, sql),
        ]
    return "\n".join(parts) + "\n"
